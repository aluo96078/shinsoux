#!/usr/bin/env python3 -I
"""Embeds the guest module in the iOS host library: embed-module.py <module.wasm> <out.c>."""
import sys

data = open(sys.argv[1], "rb").read()
with open(sys.argv[2], "w") as out:
    out.write("/* Generated by wasm/embed-module.py from shinsou_sandbox.wasm. Do not edit. */\n")
    out.write("#include <stddef.h>\n")
    out.write("const unsigned char ssc_wasm_module[] = {\n")
    for i in range(0, len(data), 24):
        out.write("  " + ", ".join(str(b) for b in data[i:i + 24]) + ",\n")
    out.write("};\n")
    out.write(f"const size_t ssc_wasm_module_len = {len(data)};\n")
