"""Embeds the compatibility bootstrap as a C string.

Until the lexbor-backed DOM bootstrap lands (ADR-0002 §17, increment c2), the sandbox evaluates
the iOS engine's bootstrap verbatim, so sandboxed scripts see exactly the reviewed engines' API.

usage: embed-bootstrap.py <IosJavaScriptBootstrap.kt> <out.c>
"""
import pathlib
import sys

source = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8")
marker = 'IOS_JAVASCRIPTCORE_BOOTSTRAP: String = """'
start = source.index(marker) + len(marker)
end = source.index('"""', start)
body = source[start:end]
if "${" in body:
    sys.exit("bootstrap contains Kotlin string templates; extraction would be wrong")
data = body.encode("utf-8")
lines = []
for i in range(0, len(data), 24):
    lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
out = pathlib.Path(sys.argv[2])
out.write_text(
    "/* Generated by scripts/embed-bootstrap.py from IosJavaScriptBootstrap.kt. Do not edit. */\n"
    "#include <stddef.h>\n"
    "const char ssc_bootstrap_js[] = {\n" + "\n".join(lines) + "\n    0x00\n};\n"
    f"const size_t ssc_bootstrap_js_len = {len(data)};\n",
    encoding="utf-8",
)
